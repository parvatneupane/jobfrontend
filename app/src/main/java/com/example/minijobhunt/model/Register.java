package com.example.minijobhunt.model;

public class Register {
    private int id;
    private String name;
    private String email;
    private String role;
    private String status;

    public int getId() {
        return id;
    }

    public String getName() {
        return name;
    }

    public String getEmail() {
        return email;
    }

    public String getRole() {
        return role;
    }

    public String getStatus() {
        return status;
    }
}
